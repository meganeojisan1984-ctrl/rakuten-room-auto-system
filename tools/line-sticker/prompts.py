STEP4 = """\
【役割】グリーンバックのモーション動画を、LINE申請用のAPNGに変換する。

【入力】グリーンバックのモーション動画（複数本）
【出力】絶対規格を満たすAPNG 24点 + main.png + tab.png + 申請zip

【処理】
1. 有効区間の判定
   各動画の全フレームを走査し、背景が緑で覆われている区間だけを抽出する。
   背景が情景に切り替わっている区間は使わない。区間の一覧を先に報告すること。
2. 切り出し
   有効区間から1.5秒（24fps＝36フレーム）ずつを1候補として切り出す。
3. キーイング
   ・背景の緑をフレーム外周から実測し、その値を基準にアルファを求める（固定閾値にしない）
   ・アンチエイリアス部は背景色に対してアンプリマルチプライし、緑の縁を除去する
   ・キャラクターに緑は使われていない前提で、緑チャンネルの突出を抑える（スピル除去）
4. 内部透過の封じ込め ★過去に「イラスト内部が透過されています」でリジェクトされている
   ・不透明な絵柄に囲まれ、画面外へ到達できない領域をすべて不透明で塗りつぶす
   ・輪郭のアンチエイリアスは画面端までつながるので、これは潰さないこと
   ・この処理を「キーイング直後」「リサイズ後」「減色後」の3回行う
   ・特に減色後が危険。アルファ255の画素が半透明の色に割り当てられ、
     1〜7pxの不可視の穴が再発する。完全不透明な画素は不透明な色のみに割り当てる
5. 配置
   320×270に収める。拡大率はカット内の全フレームを合成したバウンディングボックスで決める
   （フレームごとに決めると再生中に大きさがちらつく）。全辺10px以上あける。
6. フレーム数と再生時間
   ・20フレーム × 1/10秒 ＝ 1ループ2.000秒、ループ回数2回 ＝ 合計4.000秒
   ・delayは分数（APNGのdelay_num / delay_den）で書き、端数を出さない
   ・1フレーム目は必ずキャンバス全面で書き出す（ループ時に前の状態が残らないようにする）
7. 容量調整
   ・容量が上限を超える場合は減色してよいが、必ずRGBAとして書き出す（インデックスカラー禁止）
   ・48色を下回ると面積の小さい彩度の高い色（口の赤など）が落ちる。
     色数を48より下げる前に、フレーム数を20→16→12の順で削る
8. main.png / tab.png
   ・main.pngは240×240のAPNG。スタンプ01と同じカットから作り、ループ回数も揃える
   ・tab.pngは96×74の静止透過PNG。1フレームだけを、そのフレーム自身の
     バウンディングボックスで配置する（カット全体の合成bboxを使うと、
     tabに映らないポーズに合わせてキャラクターが縮む）

【検証】出力前に全ファイルを機械的に確認する。1件でも失敗したら作り直してから提出する
・PNGのcolour typeが6であること
・acTLのnum_playsが1〜4であること
・fcTLのdelayの合計が1/2/3/4秒ちょうどで、×num_playsが4秒以内であること
・フレーム数が5〜20、サイズが320×270、余白が全辺10px以上であること
・1ファイル1MB以下であること
・全フレームについて、不透明な絵柄に囲まれた透過画素が0であること
・四隅のアルファが0であること
・zipがフラット構成で、main.png / tab.png / 01.png〜24.png が揃っていること

【報告】検証結果を項目ごとに実測値で報告する。「規格を満たしています」だけの報告は不可。
"""

